export type YearKey = "2024" | "2025";

export interface YearSummary {
  avg_price: number;
  avg_mc: number;
  battery_mw_yr: number;
  peaker_mw_yr: number;
  battery_total_m: number;
  peaker_total_m: number;
  peaker_hours: number;
  peaker_pct: number;
  /** real avg $/MWh fuel+O&M cost, weighted across the intervals the peaker actually ran */
  avg_mc_running: number;
  /** real avg $/MWh the battery paid to recharge (before round-trip loss adjustment) */
  avg_charge_price: number;
}

export interface YearData {
  /** [month 0-11][hour 0-23] average real $/MWh price */
  heat_avg: number[][];
  /** [month 0-11][hour 0-23] % of real intervals clearing that month's peaker cost */
  heat_pct: number[][];
  /** [month 0-11][hour 0-23] % of days this hour is in the battery's top-2 discharge window */
  batt_heat: number[][];
  /** hour-of-day "1".."24" -> % of days discharging */
  batt_discharge: Record<string, number>;
  /** hour-of-day "1".."24" -> % of days charging */
  batt_charge: Record<string, number>;
  /** month "1".."12" -> battery $M at 485MW/2-hr */
  econ_battery: Record<string, number>;
  /** month "1".."12" -> peaker $M at 400MW */
  econ_peaker: Record<string, number>;
  /** month "1".."12" -> real hours the peaker cleared its cost */
  econ_peaker_hrs: Record<string, number>;
  /** month "1".."12" -> real EIA Henry Hub $/MMBtu */
  gas_price_month: Record<string, number>;
  /** month "1".."12" -> computed peaker marginal cost $/MWh */
  mc_month: Record<string, number>;
  summary: YearSummary;
}

export interface DurationPoint {
  /** battery duration, hours */
  d: number;
  /** MW buyable at $1B for this duration (Lazard duration-cost curve) */
  mw: number;
  /** $/MW-yr operating margin at that duration */
  rev_per_mw: number;
  /** total $M/yr at $1B scale */
  total_m: number;
}

